// Generates src/app/shared/india-map.ts: a lighter copy of the @svg-maps/india
// outline for the network map. The source has up to five decimals and thousands
// of sub-pixel steps; the map is never drawn wider than ~640 px (about one pixel
// per unit), so this keeps one decimal, drops detail under ~half a pixel
// (Ramer–Douglas–Peucker) and writes compact relative coordinates.
//   node scripts/simplify-india-map.mjs
import { writeFile } from 'node:fs/promises';

const { default: india } = await import('@svg-maps/india');
const EPSILON = Number(process.env.EPS ?? 0.6);
// Islands and other small rings (Lakshadweep, the Andamans) keep their full shape at
// two decimals; nothing is ever dropped from the map.
const SMALL = 3;

function parse(d) {
  const tokens = d.match(/[mMlLzZ]|-?\d*\.?\d+(?:e[-+]?\d+)?/g);
  const rings = [];
  let ring = null;
  let cmd = 'm';
  let x = 0;
  let y = 0;
  let sx = 0;
  let sy = 0;
  for (let i = 0; i < tokens.length; ) {
    const t = tokens[i];
    if (/^[mMlLzZ]$/.test(t)) {
      cmd = t;
      i++;
      if (cmd === 'z' || cmd === 'Z') {
        x = sx;
        y = sy;
        ring = null;
      }
      continue;
    }
    const a = parseFloat(tokens[i]);
    const b = parseFloat(tokens[i + 1]);
    i += 2;
    const rel = cmd === cmd.toLowerCase();
    x = rel ? x + a : a;
    y = rel ? y + b : b;
    if (cmd === 'm' || cmd === 'M') {
      ring = [[x, y]];
      rings.push(ring);
      sx = x;
      sy = y;
      cmd = rel ? 'l' : 'L'; // subsequent pairs are implicit line-tos
    } else {
      if (!ring) {
        ring = [[sx, sy]];
        rings.push(ring);
      }
      ring.push([x, y]);
    }
  }
  return rings;
}

function rdp(points, eps) {
  if (points.length < 3) return points;
  const [x1, y1] = points[0];
  const [x2, y2] = points[points.length - 1];
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = Math.hypot(dx, dy) || 1e-9;
  let max = 0;
  let idx = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const d = Math.abs(dy * px - dx * py + x2 * y1 - y2 * x1) / len;
    if (d > max) {
      max = d;
      idx = i;
    }
  }
  if (max <= eps) return [points[0], points[points.length - 1]];
  return [...rdp(points.slice(0, idx + 1), eps).slice(0, -1), ...rdp(points.slice(idx), eps)];
}

/** Shortest decimal string: 0.5 → '.5', -1.2 → '-1.2', 3 → '3'. */
const fmt = (v) => {
  let t = String(Math.round(v * 100) / 100);
  if (t.startsWith('0.')) t = t.slice(1);
  else if (t.startsWith('-0.')) t = '-' + t.slice(2);
  return t;
};
let before = 0;
let after = 0;
const locations = india.locations.map((loc) => {
  before += loc.path.length;
  const parts = [];
  for (const ring of parse(loc.path)) {
    const xs = ring.map((p) => p[0]);
    const ys = ring.map((p) => p[1]);
    const small = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) < SMALL;
    const q = small ? 100 : 10; // quantisation steps per unit
    const eps = small ? 0 : EPSILON;
    // Split closed rings at the farthest point so RDP keeps their shape.
    let far = 0;
    let best = 0;
    ring.forEach(([px, py], i) => {
      const d = Math.hypot(px - ring[0][0], py - ring[0][1]);
      if (d > best) {
        best = d;
        far = i;
      }
    });
    const simplified = [...rdp(ring.slice(0, far + 1), eps).slice(0, -1), ...rdp(ring.slice(far).concat([ring[0]]), eps).slice(0, -1)];
    // Round in absolute space first so relative steps never accumulate error.
    const abs = simplified.map(([px, py]) => [Math.round(px * q), Math.round(py * q)]);
    const pts = abs.filter((p, i) => i === 0 || p[0] !== abs[i - 1][0] || p[1] !== abs[i - 1][1]);
    if (pts.length < 3) continue; // zero-area ring: invisible in the source as well
    const num = (steps) => fmt(steps / q);
    let d = `M${num(pts[0][0])} ${num(pts[0][1])}l`;
    let prev = '';
    for (let i = 1; i < pts.length; i++) {
      for (const v of [pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]]) {
        const t = num(v);
        // No space needed before a minus sign, or before a leading '.' when the
        // previous number already has its decimal point ('1.2.5' reads 1.2, .5).
        const sep = prev === '' || t.startsWith('-') || (t.startsWith('.') && prev.includes('.')) ? '' : ' ';
        d += sep + t;
        prev = t;
      }
    }
    parts.push(d + 'z');
  }
  const path = parts.join('');
  after += path.length;
  return { id: loc.id, path };
});

const out = `/**
 * India state outlines for the network map.
 *
 * Generated by scripts/simplify-india-map.mjs from @svg-maps/india
 * (CC BY 4.0, https://github.com/VictorCazanave/svg-maps): coordinates
 * rounded to one decimal and detail under ${EPSILON} units removed, which is
 * invisible at the sizes the map is drawn. Do not edit by hand.
 */
export const INDIA_MAP = {
  viewBox: ${JSON.stringify(india.viewBox)},
  locations: ${JSON.stringify(locations)},
};
`;
await writeFile(new URL('../src/app/shared/india-map.ts', import.meta.url), out);
console.log(`India map: ${before} → ${after} path characters (${Math.round((after / before) * 100)}%)`);
